<h2>Terms and Conditions</h2>

<p>To receive the special accommodation rates, bookings must be made via Conference Logistics and not with the hotels directly. Please note that accommodation rates offered directly through the hotel or other websites may vary. Online bookings through the conference website are a guaranteed rate and reservation. Accommodation is available for the dates IN: 25/07/2017 - OUT: 1/08/2017, but may be organised outside of these dates on a 'request' only basis. If you require accommodation outside of the available dates, please select the dates that the system allows and make a note in the Special Requirements field of the additional dates you require. The closing date for accommodation bookings is 23 June 2017. Bookings made after this date will be subject to availability. All rates are per room, per night and do not include breakfast.</p>

<h3>Payments</h3>
<p>No booking will be confirmed without a credit card guarantee or a pre-payment. Any incidental expenses incurred during your stay (for example: mini bar, telephone or dry cleaning) must be paid for by yourself on check out.</p>

<h3>Accounts</h3>
<p>Delegates are responsible for paying the balance of their account and all incidentals on departure from the hotel. The hotel will be responsible for issuing tax invoices for accommodation payments upon departure.</p>

<h3>Change of Booking</h3>
<p>All amendments to your accommodation booking MUST be made in writing to Conference Logistics and not directly with the hotel. Any changes must be advised by 23 June 2017.</p>

<h3>Cancellation</h3>
<p>All cancellations MUST be made in writing to Conference Logistics. Cancellations received after 23 June 2017 will be charged by the hotel according to their cancellation policy.</p>

<h3>Arrival Time</h3>
<p>Standard hotel check-in time is 2pm, but individual hotels may differ. If you are to arrive before this time it is probable that you will not be able to gain access to your room. To guarantee a room to be available for an early arrival you will need to pre-book your room for the previous night. If required, please indicate on your registration form. (You will be charged by the hotel for the additional night).</p>



