<h1>Support and prizes</h1>

<span class="contentListTitle">SUPPORT FOR YOUNG PARTICIPANTS</span>

<p>Limited funds are available to support young participants presenting invited talks or contributed posters. Participants from developing regions and students will be prioritised. An application letter with signature should be submitted to <a href="mailto:icpeac30@conlog.com.au">icpeac30@conlog.com.au</a> before 20 February 2017 (ATTN: ICPEAC Financial Support). Applicants will be notified of the outcome of the decision by March 2017.</p>

<p>The XXX ICPEAC organizing committee encourages potential Australian student participants to join the Australian Institute of Physics to become eligible for the conference support.</p>

<p>The <a href="http://aip.org.au/aip-member-benefits-and-services/#2">conference support scheme</a> is available to postgraduate students who have been members of the AIP for at least 6 months prior to the closing date for applications. For the XXX ICPEAC  this will be the 31st August 2017 round although the application may be submitted earlier.</p>

<span class="contentListTitle">PRIZES</span>
<p>The <a href="http://iupap.org/c15-news/">IUPAP Young Scientist Prize</a> in Atomic, Molecular, and Optical Physics was awarded to Dr. Johannes Feist, Universidad Autónoma de Madrid, Spain, for his outstanding contributions in modifications of molecular structure under strong light-matter coupling</p>

<p>The <a href="http://www.ucd.ie/icpeac/sheldon_prize.html">Sheldon Datz Prize</a> for an Outstanding Young Scientist attending ICPEAC was awarded to Dr. Dermot Green, Queen's University of Belfast,   for advances in Many-body theory of positronium-atom scattering</p>

<p>ICPEAC Daily Poster Prizes were awarded to</p>
<ul>
<li>Sven Grundmann, Goethe-Universität Frankfurt, Germany
Observation of electron back-to-back emission from the quasi-free mechanism of helium at 800 eV photon energy</li>

<li>Dr Dalong Guo, Chinese Academy of Sciences
Investigation of fragmentation dynamics of nitrogen dimers by collisions with highly charged ions</li>

<li>Prof Chenzhong Dong, Northwest Normal University, China
Evolution analysis of EUV radiation from laser-produced tin plasmas</li>

<li>Sebastian Eckart, Goethe University Frankfurt, Germany
Ring Currents in Single Atoms – Ultrafast Preparation and Detection using Strong Field Ionization</li>

<li>Kilian Fehre, Goethe University Frankfurt, Germany
Absolute detection efficiencies for multi coincidence studies</li>
</ul>


 
