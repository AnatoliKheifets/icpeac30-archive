              <p>South Bank stretches from Queensland Art Gallery and Gallery of Modern Art in the north to the Queensland Maritime Museum in the south and is famous for its diverse mix of entertainment, recreation and leisure activities that are all within walking distance of each other. Just some of the precinct’s highlights include 17 hectares of inner-city parklands; more than 90 restaurants, cafes, bars and boutiques; world-class museums and galleries; a performing arts centre; a cinema; five-star hotels and the Wheel of Brisbane.</p>
