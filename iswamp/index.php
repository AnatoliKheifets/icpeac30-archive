            <td align="left" valign="top" class="content"><h1>Welcome</h1>
              
              <div class="introText">
                <p>July 22-24, 2017, Ship Inn, South Bank, Brisbane, Australia</p></div>
<p>
After ISWAMP-1 in Dublin (Ireland) in 2011, ISWAMP-2 in Xi’an (China) in 2013 and ISWAMP-3 (Germany) in 2015, the fourth workshop of this series ISWAMP-4 will take place in Brisbane (Australia) before ICPEAC 2017, which will be held from 26th of July to 1st of August, 2017 in Cairns, Australia. ISWAMP-4 will begin in the afternoon of July 22nd, 2017 (with registration opening around noon) and will close in the afternoon of July 24th, 2017. Leaving the day of July 25st free in order to reach the welcome reception and reception of ICPEAC 2017 on the following day.
</p>
              <p>Intense field- Short Wavelength Atomic and Molecular Processes（ISWAMP） is an official Satellite workshop of the International Conference on Photonic, Electronic and Atomic Collisions (ICPEAC). ISWAMP is designed to provide a focus for the strongly growing community of AMO scientists who are working on the interaction of atomic systems with intense laser fields extending from the UV through the Extreme-UV (EUV) and on to the X-ray region of the electromagnetic spectrum. It is also designed to provide a focus for the complementary field of high harmonic generation (HHG) and attosecond science.<br />
<br />

Presentations will include plenary talks, invited talks and contributed talks as well as one poster session. All topics for ISWAMP-4 will be within the studies related to the atomic and molecular processes in intense, short-wavelength optical field, as follows:</p>
             <ul>
		<li>Excitation, ionization and fragmentation in intense EUV and X-ray fields</li>
               <li>Non-linear processes in EUV and X-ray</li>
               <li>Developments in short-wavelength free electron lasers</li>
               <li>Developments in HHG-attosecond light sources</li>
               <li>Instrumentation for ISWAMP</li>
               <li>New approaches to intense UV and X-ray generation</li>
                           
                </ul>

