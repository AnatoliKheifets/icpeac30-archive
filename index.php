<h1>MESSAGE FROM ORGANIZERS</h1>

<p>We warmly thank the delegates, accompanying persons, sponsors and exhibitors who took part in the 30th International Conference on Photonic, Electronic and Atomic Collisions (ICPEAC XXX) in Cairns, Australia, from 26 July to 1 August 2017 at the Cairns Convention Centre. This conference continued the nearly sixty-year history of the ICPEAC series which began in New York, USA, in 1958 and held biennially since 1961.</p>

<img src="_images/Cairns_panorama-594x151.jpg" width="594" height="151" />
 
<p>With attendance very close to 500 participants, ICPEAC XXX brought together world's leading scientists who worked actively in the fields of collisions involving photons, electrons, ions, atoms, molecules, clusters, surfaces, and exotic particles. The ICPEAC XXX scientific program was carefully selected by the International Program Committee. It was led by distinguished tutorial and plenary lecturers who highlighted the recent discoveries in their field of research. This was followed by nearly 60 progress reports which gave further details and in-depth analysis of many important works. Close to 600 original presentations were exhibited in 5 poster sessions with the best poster selected daily by the popular vote and 25 "hot topic" presentations promoted to oral talks.</p> 
<p>The ICPEAC XXX was hosted in the award-winning Cairns Convention Centre and looked after by the professional and dedicated team of Conference Logistics who made the conference program running smoothly.</p>
<p>The delegates and guests enjoyed the vigorous social program. They were welcome to the country by traditional land owners, entertained by animal handlers and the aboriginal dance company, dined in recreated tropical environment and were lectured on the most dangerous creatures living in Australian waters. The week-end was full of excitement with trips to the coral reef, hinterland, rainforest and the crocodile farm.</p>
<p>We very much hope that your experience at the ICPEAC XXX was great and you had been both enlightened and entertained by the conference. We trust it was a memorable event and a great reward to those of you who battled great distances to come to the Australian shores.</p>
